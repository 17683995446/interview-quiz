def pick_diff():
    r = random.random()
    return "easy" if r < 0.4 else ("medium" if r < 0.8 else "hard")

def shuf(opts, ci):
    idx = list(range(len(opts)))
    random.shuffle(idx)
    return [opts[i] for i in idx], idx.index(ci)

def mkc(qid, cat, q, opts, ans, exp):
    opts, ans = shuf(opts, ans)
    return {"id":qid,"cat":cat,"diff":pick_diff(),"type":"choice","q":q,"opts":opts,"ans":ans,"exp":exp}

def mktf(qid, cat, q, ab, exp):
    return {"id":qid,"cat":cat,"diff":pick_diff(),"type":"truefalse","q":q,"opts":["正确","错误"],"ans":0 if ab else 1,"exp":exp}

